package main

// font5x7 encodes bitmap glyphs as 7 row-masks. Bit (4-col) of each mask
// selects column col, so bit 4 = leftmost pixel and bit 0 = rightmost.
var font5x7 = map[byte][7]uint8{
	' ': {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
	'Y': {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04},
	'a': {0x00, 0x0E, 0x01, 0x0F, 0x11, 0x0F, 0x00},
	'e': {0x00, 0x0E, 0x11, 0x1F, 0x10, 0x0E, 0x00},
	'g': {0x00, 0x0E, 0x11, 0x11, 0x0F, 0x01, 0x0E},
	'h': {0x10, 0x10, 0x1E, 0x11, 0x11, 0x11, 0x00},
	'l': {0x0C, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E},
	'm': {0x00, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x00},
	'o': {0x00, 0x0E, 0x11, 0x11, 0x11, 0x0E, 0x00},
	's': {0x00, 0x0E, 0x10, 0x0E, 0x01, 0x0E, 0x00},
	't': {0x04, 0x04, 0x1F, 0x04, 0x04, 0x03, 0x00},
	'u': {0x00, 0x11, 0x11, 0x11, 0x11, 0x0E, 0x00},
}

const (
	fontW = 5
	fontH = 7
)

func drawText(text string, x, y, scale int, color uint32) {
	for i := range len(text) {
		rows, ok := font5x7[text[i]]
		if !ok {
			rows = font5x7[' ']
		}
		for row := range fontH {
			for col := range fontW {
				if rows[row]&(1<<(fontW-1-col)) != 0 {
					for dy := range scale {
						for dx := range scale {
							writePixel(x+col*scale+dx, y+row*scale+dy, color)
						}
					}
				}
			}
		}
		x += (fontW + 1) * scale
	}
}

func textWidth(text string, scale int) int {
	n := len(text)
	if n == 0 {
		return 0
	}
	return ((fontW+1)*n - 1) * scale
}
